function detectSystemLocale(): Locale {
  const lang = navigator.language.toLowerCase();
  if (lang.startsWith('zh')) return 'zh';
  return 'en';
}

function loadSavedLocale(): Locale | null {
  try { return localStorage.getItem('locale') as Locale | null; } catch { return null; }
}

let currentLocale: Locale = loadSavedLocale() ?? detectSystemLocale();

export const locale = writable<Locale>(currentLocale);

locale.subscribe((value) => {
  currentLocale = value;
  try { localStorage.setItem('locale', value); } catch { /* ignore */ }
});

export function setLocale(l: Locale) { locale.set(l); }

export function t(key: string, params?: Record<string, string>): string {
  let text = translations[currentLocale][key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(`{{${k}}}`, v);
    }
  }
  return text;
}

